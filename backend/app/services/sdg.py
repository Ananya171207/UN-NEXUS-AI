"""Country SDG signals: real World Bank indicator values grouped under the goals they relate to.

What this is NOT: an SDG progress score. There is no "on track / off track", no
percentage of a target reached, and no ranking. A signal is one real indicator
value with its year, unit and source. Goals are taken from the `sdgs` tuple of
each indicator in `services/worldbank.INDICATORS` (the single registry).

`relation` is honest about how close an indicator is to the official UN SDG
indicator framework:
  * "matches_sdg_indicator": the World Bank series is the same measure as the named
    UN SDG indicator (`sdgIndicator`).
  * "related_context": relevant to the goal but not an official SDG indicator
    (for example GDP growth, or renewable share of electricity output, which is
    not the official 7.2.1 measure of final energy consumption).
Anything with unknown classification defaults to "related_context".
"""
from __future__ import annotations

from datetime import datetime, timezone

from app.config import settings
from app.services import worldbank

SDG_NAMES: dict[int, str] = {
    1: "No Poverty", 2: "Zero Hunger", 3: "Good Health and Well-being", 4: "Quality Education",
    5: "Gender Equality", 6: "Clean Water and Sanitation", 7: "Affordable and Clean Energy",
    8: "Decent Work and Economic Growth", 9: "Industry, Innovation and Infrastructure",
    10: "Reduced Inequalities", 11: "Sustainable Cities and Communities",
    12: "Responsible Consumption and Production", 13: "Climate Action", 14: "Life Below Water",
    15: "Life on Land", 16: "Peace, Justice and Strong Institutions", 17: "Partnerships for the Goals",
}

# indicator key -> (UN SDG indicator it matches or None, plain-language explanation)
INDICATOR_INFO: dict[str, tuple[str | None, str]] = {
    "gdp": (None, "Total value of goods and services produced in the country in a year, in current US dollars."),
    "gdp_per_capita": (None, "Average economic output per person, in current US dollars. An average: it does not show how income is shared."),
    "gdp_growth": (None, "Yearly percentage change in total GDP. Related to, but not the same as, the official SDG 8.1.1 (real GDP per capita growth)."),
    "inflation": (None, "Yearly percentage change in consumer prices: how fast the cost of living is rising."),
    "unemployment": ("8.5.2", "Share of the labour force that is without work but available and looking for it."),
    "life_expectancy": (None, "Average number of years a newborn would live if current death rates stayed the same. A broad health outcome."),
    "school_enrollment": (None, "Secondary-school pupils (any age) as a share of the official secondary-school-age population. Can exceed 100%. Measures access, not learning quality."),
    "poverty_rate": ("1.1.1", "Share of people living below the international poverty line (World Bank)."),
    "undernourishment": ("2.1.1", "Share of people whose usual food intake is too low to meet their energy needs."),
    "drinking_water": ("6.1.1", "Share of people using a drinking-water source on premises, available when needed and free of contamination."),
    "internet_use": (None, "Share of people who used the Internet in the last three months. Relevant to access to digital infrastructure (SDG 9)."),
    "co2_emissions": (None, "Carbon dioxide emissions per person, excluding land use change. Relevant to climate action; says nothing about adaptation."),
    "renewable_electricity": (None, "Share of electricity generated from renewable sources. The official SDG 7.2.1 measures renewables in total final energy consumption instead."),
    "pm25": ("11.6.2", "Average yearly exposure to fine particles (PM2.5) in urban air, in micrograms per cubic metre."),
    "forest_area": ("15.1.1", "Forest as a share of the country's land area."),
}

METHODOLOGY = (
    "Each signal is the most recent value the World Bank has for one indicator. Values are not "
    "combined into scores and are not compared with targets, so this endpoint does not say whether "
    "a country is on track. Years differ between indicators; always read the value together with "
    "its year. Nothing on this endpoint is generated by AI."
)


def _current_year() -> int:
    return datetime.now(timezone.utc).year


def _signal(result: dict, *, now_year: int) -> dict:
    key = result["key"]
    sdg_indicator, explanation = INDICATOR_INFO.get(key, (None, result.get("label") or key))
    year = result.get("year")
    age = now_year - int(year) if isinstance(year, str) and year.isdigit() else None
    status = result["status"]
    return {
        "indicatorKey": key,
        "indicatorName": result.get("indicatorName") or result.get("label"),
        "indicatorCode": result.get("sourceCode"),
        "value": result.get("value") if status == "available" else None,
        "year": year if status == "available" else None,
        "unit": result.get("unit"),
        "source": result.get("source"),
        "availability": status,  # available | no_data | error | pending
        "stale": bool(result.get("stale")),
        "outdated": bool(status == "available" and age is not None and age > settings.sdg_outdated_years),
        "relation": "matches_sdg_indicator" if sdg_indicator else "related_context",
        "sdgIndicator": sdg_indicator,
        "explanation": explanation,
        "fetchedAt": result.get("fetchedAt"),
        "error": result.get("error"),
    }


def build_signals(country: dict, results: dict[str, dict], *, only: set[int] | None = None,
                  now_year: int | None = None) -> dict:
    """Group indicator results under their goals. Pure function (no network)."""
    year_now = now_year or _current_year()
    by_goal: dict[int, list[dict]] = {}
    for indicator in worldbank.INDICATORS:
        result = results.get(indicator.key)
        if result is None:
            continue
        for goal in indicator.sdgs:
            by_goal.setdefault(goal, []).append(_signal(result, now_year=year_now))

    goals = []
    for number in sorted(by_goal):
        if only and number not in only:
            continue
        signals = by_goal[number]
        available = sum(1 for s in signals if s["availability"] == "available")
        goals.append({
            "sdg": number, "name": SDG_NAMES.get(number, f"SDG {number}"),
            "signals": signals, "availableCount": available, "totalCount": len(signals),
            "hasData": available > 0,
        })
    covered = {g["sdg"] for g in goals}
    return {
        "countryId": country["id"], "countryCode": country["code"], "countryName": country["name"],
        "dataType": "indicator_values", "aiGenerated": False,
        "source": worldbank.SOURCE_NAME, "methodology": METHODOLOGY,
        "goals": goals,
        "goalsWithoutIndicators": [n for n in sorted(SDG_NAMES) if n not in covered and not only],
        "outdatedAfterYears": settings.sdg_outdated_years,
    }


def get_signals(country: dict, only: set[int] | None = None) -> dict:
    results = worldbank.fetch_country_indicators(country["code"])
    return build_signals(country, results, only=only)


def all_unavailable(signals: dict) -> bool:
    """True when nothing could be loaded at all (every indicator failed or still loading)."""
    items = [s for g in signals["goals"] for s in g["signals"]]
    return bool(items) and all(s["availability"] in ("error", "pending") for s in items)
